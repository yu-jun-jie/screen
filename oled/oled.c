#include "oled.h"

#define OLED_IIC_ADDERS	(0x3C << 1)

#define iicwrite(ADD,DATA,LEN)  HAL_I2C_Master_Transmit(&hi2c2, ADD, DATA, LEN, 10)

extern const unsigned char fonts_8x8[8*95];
extern const unsigned char fonts_8x16[16*95];

void oledinit(void){
    uint8_t reg[] = {0x00,0x8D,0x14,0xAF};
    iicwrite(OLED_IIC_ADDERS,reg,4);
}

void oledsetxy(uint8_t x,uint8_t y){
    uint8_t reg[] = {0x00,0xB0,0x10,0x00};

    reg[2] = 0x10|(x>>4);
    reg[3] = 0x00|(x&0x0F);
    reg[1] = 0xB0+y;

    iicwrite(OLED_IIC_ADDERS,reg,4);
}

void oleddat(uint8_t x,uint8_t y,uint8_t dat){
    uint8_t reg2[2] = {0x40,0x00};
    reg2[1] = dat;
    oledsetxy(x,y);
    iicwrite(OLED_IIC_ADDERS,reg2,2);
}

void oledfontx8y8(uint8_t x,uint8_t y,char *str){
    uint8_t i=0;
    uint8_t reg2[2] = {0x40,0x00};
    char *pstr = str;
    oledsetxy(x,y);
    while(*pstr >= ' ' && *pstr <= '~'){
        for(i=0;i<8;++i){
            reg2[1] = fonts_8x8[(*pstr-' ')*8+i];
            iicwrite(OLED_IIC_ADDERS,reg2,2);
        }
        pstr++;
    }
}
